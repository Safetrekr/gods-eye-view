function inverse(table, n) {
  const m = new Map();
  for (let i = n - 1; i >= 1; i--)
    m.set((table[i * 3] << 16) | (table[i * 3 + 1] << 8) | table[i * 3 + 2], i);
  return m;
}
const N0Q_INV = inverse(N0Q_RGB, 256);
const EET_INV = inverse(EET_RGB, 72);
const nearCache = new Map();

function nearest(table, n, key, r, g, b) {
  const ck = `${key}:${(r << 16) | (g << 8) | b}`;
  if (nearCache.has(ck)) return nearCache.get(ck);
  let best = 0;
  let bd = Infinity;
  for (let i = 1; i < n; i++) {
    const d =
      (table[i * 3] - r) ** 2 +
      (table[i * 3 + 1] - g) ** 2 +
      (table[i * 3 + 2] - b) ** 2;
    if (d < bd) {
      bd = d;
      best = i;
    }
  }
  // Too far from any palette colour: not a radar pixel (labels, edges).
  const out = bd <= 900 ? best : 0;
  if (nearCache.size > 4096) nearCache.clear();
  nearCache.set(ck, out);
  return out;
}

/** n0q RGB → dBZ (null = no echo). */
export function n0qDbz(r, g, b) {
  const k = (r << 16) | (g << 8) | b;
  const i = N0Q_INV.get(k) ?? nearest(N0Q_RGB, 256, 'n', r, g, b);
  return i ? i * 0.5 - 32.5 : null;
}

/** Echo-tops RGB → storm top in thousands of feet (null = no echo). */
export function eetKft(r, g, b) {
  const k = (r << 16) | (g << 8) | b;
  const i = EET_INV.get(k) ?? nearest(EET_RGB, 72, 'e', r, g, b);
  return i || null;
}
